/**
 * 回归:专项附加扣除「申报月数」月粒度含首尾
 * 规则:边界日期落在某月任意一天 → 该月计入。
 *  赡养老人:满 60 周岁当月起算(1964-05-15 → 2024 满60 → 报 8 个月 5~12;1964-12-01 → 1;
 *    1965-06-01 → 2025 满60 → 7;未满 60(1970-01) → 不设;早满60(1959-07) → 恒 12)
 *  3岁以下婴幼儿照护:出生当月~满 3 周岁当月(2022-05-15 → 出生年 2022 报 8;中间年 2024 报 12;
 *    满3周岁年 2025 报 5)
 *  子女教育:时间段与当年相交月(仅开始 2023-09-01 → 报 4;仅结束 2025-07-31 → 报 7)
 */
'use strict';
var path = require('path');
var BASE = path.join(__dirname, '..', 'content') + '/';
var T = { DEDUCT_YEARS_OFFSET: -4 };
global.window = { __taxExport: T };
require(BASE + 'mask.js');     // 真实脱敏(payload 依赖)
require(BASE + 'payload.js');  // 真实申报月数算法

function detail(y, tabs) {
  return {
    '_申报项目': y + '年度综合所得年度汇算', '_税款所属期': '', '_申报状态': '',
    '_detail_sections': { '计税详情': { 收入表: [], 汇总: {} }, '专项附加扣除明细': tabs }
  };
}
var job = {
  deductionYears: [2022, 2023, 2024, 2025],
  details: [
    detail(2022, {
      '3岁以下婴幼儿照护': [{ '子女姓名': '周婴', '出生日期': '2022-05-15' }]
    }),
    detail(2023, {
      '子女教育': [{ '子女姓名': '周小', '当前受教育阶段开始时间': '2023-09-01' }]
    }),
    detail(2024, {
      '赡养老人': [
        { '被赡养人姓名': '杨A', '出生日期': '1964-05-15' },
        { '被赡养人姓名': '杨B', '出生日期': '1964-12-01' }
      ],
      '3岁以下婴幼儿照护': [{ '子女姓名': '周婴', '出生日期': '2022-05-15' }]
    }),
    detail(2025, {
      '赡养老人': [
        { '被赡养人姓名': '杨C', '出生日期': '1959-07-03' },
        { '被赡养人姓名': '杨D', '出生日期': '1970-01-01' }
      ],
      '3岁以下婴幼儿照护': [{ '子女姓名': '周婴', '出生日期': '2022-05-15' }],
      '子女教育': [{ '子女姓名': '周小', '当前受教育阶段结束时间': '2025-07-31' }]
    })
  ]
};
var payload = T.payload.transform(job);
var settle = payload['年度汇算'];
function months(y, proj, idx) {
  var arr = (settle[y] && settle[y]['专项附加扣除'] || []).filter(function (it) { return it['项目'] === proj; });
  return arr.length ? arr[idx == null ? 0 : idx]['申报月数'] : undefined;
}
var fails = [];
function check(actual, want, m) {
  if (actual !== want) fails.push(m + '(期望 ' + want + ',实 ' + actual + ')');
  else console.log('  ✓ ' + m + ' = ' + actual);
}
check(months('2024', '赡养老人', 0), 8, '赡养老人 1964-05-15 满60当月计入 → 2024 报 8 个月(5~12)');
check(months('2024', '赡养老人', 1), 1, '赡养老人 1964-12-01 满60当月计入 → 2024 报 1 个月(12)');
check(months('2025', '赡养老人', 0), 12, '赡养老人 1959-07-03 早满60 → 2025 恒 12');
check(months('2025', '赡养老人', 1), undefined, '赡养老人 1970-01-01 未满60 → 2025 不设申报月数');
check(months('2022', '3岁以下婴幼儿照护'), 8, '婴幼儿 2022-05-15 出生当月计入 → 出生年 2022 报 8(5~12)');
check(months('2024', '3岁以下婴幼儿照护'), 12, '婴幼儿 2022-05 生,2024 全年在3岁前 → 报 12');
check(months('2025', '3岁以下婴幼儿照护'), 5, '婴幼儿 2025-05 满3周岁当月计入 → 2025 报 5(1~5)');
check(months('2023', '子女教育'), 4, '子女教育 仅开始 2023-09-01 → 2023 报 4(9~12)');
check(months('2025', '子女教育'), 7, '子女教育 仅结束 2025-07-31 → 2025 报 7(1~7)');
console.log(fails.length ? '✗ 失败:\n  - ' + fails.join('\n  - ') : '✓ 全部通过');
process.exit(fails.length ? 1 : 0);
